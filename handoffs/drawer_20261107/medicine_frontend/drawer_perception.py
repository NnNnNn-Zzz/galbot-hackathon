"""Same-drawer red handle candidates; ambiguous scenes require a narrower ROI.

This is a geometric/color baseline, not a trained semantic detector. Output
must pass metric geometry checks before being used by drawer_open.
"""
import cv2
import numpy as np


def segment_handle(bgr, roi=None):
    if bgr is None or bgr.ndim != 3 or bgr.shape[2] != 3:
        raise ValueError("Expected BGR image")
    hsv = cv2.cvtColor(bgr, cv2.COLOR_BGR2HSV)
    mask = (((hsv[:, :, 0] < 12) | (hsv[:, :, 0] > 160))
            & (hsv[:, :, 1] > 85) & (hsv[:, :, 2] > 35)).astype('uint8')*255
    if roi is not None:
        x, y, w, h = map(int, roi)
        if x < 0 or y < 0 or w <= 0 or h <= 0 or x+w > mask.shape[1] or y+h > mask.shape[0]:
            raise ValueError("ROI outside image")
        allowed = np.zeros_like(mask)
        allowed[y:y+h, x:x+w] = 255
        mask &= allowed
    original = mask.copy()
    mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, np.ones((3, 9), np.uint8))
    contours, hierarchy = cv2.findContours(mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_SIMPLE)
    candidates = []
    for i, contour in enumerate(contours):
        if hierarchy[0, i, 3] != -1:
            continue
        x, y, w, h = cv2.boundingRect(contour)
        area = cv2.contourArea(contour)
        if area < 100 or not 1.7 <= w/max(h, 1) <= 6 or area/(w*h) < .35:
            continue
        # This handle is a rectangular ring; reject solid red labels/cups.
        child = hierarchy[0, i, 2]
        hole_area = 0
        while child != -1:
            hole_area += cv2.contourArea(contours[child])
            child = hierarchy[0, child, 0]
        center_fill = np.mean(original[y+h//3:y+2*h//3, x+w//5:x+4*w//5] > 0)
        if not (.08 <= hole_area/max(area, 1) <= .75 or center_fill < .30):
            continue
        region = np.zeros_like(mask)
        cv2.drawContours(region, [contour], -1, 255, -1)
        region &= original  # exclude filled gaps and gripper occlusion
        candidates.append({"bbox": [x, y, w, h], "mask": region.astype(bool)})
    if len(candidates) != 1:
        raise ValueError(f"handle_candidate_count:{len(candidates)}")
    return candidates[0]


def validate_correspondences(camera_points_m, base_points_m, camera_to_base,
                             *, max_rms_m=.004, max_error_m=.008):
    """Independent measured correspondences, not points generated by this transform.

    At least six points distributed across the working volume; report evidence,
    never set calibration verified based only on file existence or valid matrices.
    """
    from medicine_frontend.drawer_geometry import transform
    a, b = np.asarray(camera_points_m, float), np.asarray(base_points_m, float)
    if (a.shape != b.shape or a.ndim != 2 or a.shape[1] != 3 or len(a) < 6
            or not np.isfinite(a).all() or not np.isfinite(b).all()):
        raise ValueError("Need six paired finite 3D calibration observations")
    if np.linalg.svd(a-a.mean(0), compute_uv=False)[1] < .03:
        raise ValueError("Calibration points lack spatial coverage")
    t = transform(camera_to_base)
    errors = np.linalg.norm(a @ t[:3, :3].T+t[:3, 3]-b, axis=1)
    rms, worst = float(np.sqrt(np.mean(errors**2))), float(errors.max())
    return {"passed": rms <= max_rms_m and worst <= max_error_m,
            "rms_m": rms, "max_error_m": worst, "count": len(a)}


def decode_depth(data, *, depth_scale, encoding, shape=None):
    """SDK images are encoded; saved camera-bridge .bin files are explicit raw LE."""
    if not np.isfinite(depth_scale) or depth_scale <= 0:
        raise ValueError("Invalid depth scale")
    if encoding == "raw_uint16_le":
        if shape is None or len(data) != int(np.prod(shape))*2:
            raise ValueError("Raw depth size mismatch")
        depth = np.frombuffer(data, dtype='<u2').reshape(shape)
    elif encoding == "encoded":
        depth = cv2.imdecode(np.frombuffer(data, np.uint8), cv2.IMREAD_UNCHANGED)
        if depth is None or depth.ndim != 2 or depth.dtype != np.uint16:
            raise ValueError("Invalid encoded depth")
    else:
        raise ValueError("Unknown depth encoding")
    return depth.astype(float)/depth_scale
